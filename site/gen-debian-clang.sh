#!/usr/bin/env bash
# Build Debian's 6.1 686 kernel from its source package with clang/lld
# (LLVM=1, the clang in PATH; CI: the native clang 22.1.0 of
# gen-clang-native.sh), bzImage only, in the source tree:
#
#   site/gen-debian-clang.sh SRCDIR CONFIG [JOBS]
#   site/gen-debian-clang.sh --make SRCDIR [JOBS]   the build's make command
#                                                  again (capture-host-tools.py)
#
# SRCDIR is gen-debian-source.sh's tree, CONFIG Debian's config of
# linux-image-6.1.0-50-686 (/boot/config-6.1.0-50-686 in the package).
# Debian's certificates are not in the source, so the trusted and revoked
# key lists are emptied (the module signing key is generated by the
# build); olddefconfig then adapts the config to clang. SRCDIR/config.diff
# lists what differs from Debian's config. The build's version text is
# fixed, so it does not depend on the date or the machine. Writes
# SRCDIR/vmlinux and SRCDIR/arch/x86/boot/bzImage; the .cmd file of every
# object keeps its compile command (check-wasm-objects.mjs).
set -euo pipefail

# The bzImage build: the same command for the build and for --make.
build() {
	make ARCH=i386 LLVM=1 -j"$1" KBUILD_BUILD_VERSION=1 KBUILD_BUILD_TIMESTAMP="2026-07-04" \
		KBUILD_BUILD_USER=mkb KBUILD_BUILD_HOST=mkb bzImage
}

if [ "${1:-}" = --make ] && [ $# -ge 2 ]; then
	cd "$2"
	build "${3:-$(nproc)}"
	exit
fi
if [ $# -lt 2 ]; then
	sed -n '2,/^set /p' "$0" | sed '$d' >&2
	exit 2
fi
src=$1
config=$(realpath "$2")
jobs=${3:-$(nproc)}

cd "$src"
# Regenerated by kbuild from syscall_32.tbl (gen-debian-source.sh writes it
# for the source view without the build's dependency file).
rm -f arch/x86/include/generated/asm/syscalls_32.h
cp "$config" .config
scripts/config --set-str SYSTEM_TRUSTED_KEYS "" --set-str MODULE_SIG_KEY "certs/signing_key.pem" \
	--set-str SYSTEM_REVOCATION_KEYS "" --set-str BUILD_SALT "6.1.0-50-686"
make ARCH=i386 LLVM=1 olddefconfig >/dev/null
diff <(/usr/bin/grep -v '^#' "$config" | sort) <(/usr/bin/grep -v '^#' .config | sort) > config.diff || true
echo "config lines changed from Debian's: $(/usr/bin/grep -c '^[<>]' config.diff)"
clang --version | head -1
start=$(date +%s)
build "$jobs"
echo "Debian 6.1 686 bzImage with clang: $(( $(date +%s) - start )) s"
ls -l vmlinux arch/x86/boot/bzImage
